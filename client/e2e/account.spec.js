import { test, expect } from '@playwright/test';

test('customer registration, profile persistence, role protection and logout/login', async ({ page }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const email = `e2e-${Date.now()}@example.test`;
  const password = 'Browser test password 2026!';
  await page.goto('/#/account');
  await expect(page.getByRole('heading', { name: 'Sign in required' })).toBeVisible();
  await page.goto('/#/register');
  await page.getByLabel('Full name').fill('Browser Test Customer');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My profile' })).toBeVisible();
  const cookie = (await page.context().cookies()).find(item => item.name === 'smartrent_session');
  expect(cookie.httpOnly).toBe(true); expect(cookie.sameSite).toBe('Strict');
  await page.getByLabel('Full name').fill('Updated Browser Customer');
  await page.getByLabel('Phone (optional)').fill('+90 555 123 45 67');
  await page.getByRole('button', { name: 'Save profile' }).click();
  await expect(page.getByRole('status')).toHaveText('Profile saved.');
  await page.reload();
  await expect(page.getByLabel('Full name')).toHaveValue('Updated Browser Customer');
  await expect(page.getByLabel('Phone (optional)')).toHaveValue('+90 555 123 45 67');
  await page.screenshot({ path: testInfo.outputPath('account-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('account-mobile.png'), fullPage: true });
  await page.goto('/#/admin');
  await expect(page.getByRole('heading', { name: 'Access denied' })).toBeVisible();
  expect((await page.request.get('/api/admin/access')).status()).toBe(403);
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible();
  expect((await page.request.get('/api/me')).status()).toBe(401);
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('Incorrect password!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('Email or password is incorrect.');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByLabel('Full name')).toHaveValue('Updated Browser Customer');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible();
  await page.goto('/#/register');
  await page.getByLabel('Full name').fill('Duplicate Customer');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('Email address already registered.');
  expect(errors).toEqual([]);
});

test('protected page shows session errors and offers a working retry', async ({ page }) => {
  await page.route('**/api/me', route => route.fulfill({ status: 503, json: { error: { message: 'Unavailable' } } }));
  await page.goto('/#/account');
  await expect(page.getByRole('alert')).toContainText('Unable to check your session');
  await page.unroute('**/api/me');
  await page.getByRole('button', { name: 'Try again' }).click();
  await expect(page.getByRole('heading', { name: 'Sign in required' })).toBeVisible();
});
